#!/usr/bin/env python3
"""Vendor the architecture pages' Font Awesome Free SVG subset for offline use."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / 'apps/console/node_modules/@fortawesome/fontawesome-free'
OUTPUT = ROOT / 'docs/architecture/vendor/fontawesome'
VERSION = '6.7.2'
ALIASES = {
    'box': 'cube', 'cube': 'cube', 'layers': 'layer-group',
    'grid': 'table-cells-large', 'flow': 'diagram-project', 'folder': 'folder-open',
    'compass': 'compass', 'search': 'magnifying-glass', 'terminal': 'terminal',
    'pulse': 'wave-square', 'copy': 'copy', 'menu': 'bars', 'close': 'xmark',
    'camera': 'camera', 'phone': 'mobile-screen-button', 'robot': 'robot',
    'arm': 'robot', 'target': 'crosshairs', 'database': 'database', 'code': 'code',
    'vr': 'vr-cardboard', 'motion': 'route', 'chip': 'microchip',
    'expand': 'expand', 'download': 'download',
}


def main():
    if not PACKAGE.is_dir():
        raise SystemExit('Install the locked console dependencies: ./run.sh components setup frontend')
    package = json.loads((PACKAGE / 'package.json').read_text())
    if package['version'] != VERSION:
        raise SystemExit(f'Expected Font Awesome Free {VERSION}, found {package["version"]}')
    icons, hashes = {}, {}
    for name in sorted(set(ALIASES.values())):
        source = PACKAGE / 'svgs/solid' / f'{name}.svg'
        content = source.read_text()
        icons[name] = {
            'viewBox': re.search(r'viewBox="([^"]+)"', content).group(1),
            'body': re.search(r'<svg\b[^>]*>(.*)</svg>', content, re.DOTALL).group(1),
        }
        hashes[f'svgs/solid/{name}.svg'] = hashlib.sha256(source.read_bytes()).hexdigest()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(PACKAGE / 'LICENSE.txt', OUTPUT / 'LICENSE.txt')
    metadata = {
        'package': package['name'], 'version': VERSION,
        'source': 'https://github.com/FortAwesome/Font-Awesome/tree/6.7.2',
        'author': 'Fonticons, Inc.', 'icon_license': 'CC-BY-4.0',
        'license_url': 'https://creativecommons.org/licenses/by/4.0/',
        'changes': 'Selected upstream SVGs bundled as local symbols; paths and viewBoxes unchanged.',
        'aliases': ALIASES, 'source_sha256': hashes,
    }
    (OUTPUT / 'SOURCE.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    bundle = '''// Generated by scripts/docs/build_architecture_icons.py.
// Font Awesome Free 6.7.2 by Fonticons, Inc. — SVG icons licensed CC BY 4.0.
// https://fontawesome.com/license/free | See LICENSE.txt and SOURCE.json.
(() => {
  'use strict';
  const icons = ICON_DATA;
  const aliases = ALIAS_DATA;
  const namespace = 'http://www.w3.org/2000/svg';
  function svg(name) {
    const item = icons[aliases[name] || aliases.box];
    return `<svg class="icon" aria-hidden="true" focusable="false" viewBox="${item.viewBox}" fill="currentColor" stroke="none">${item.body}</svg>`;
  }
  function install(defs) {
    for (const [alias, name] of Object.entries(aliases)) {
      const symbol = document.createElementNS(namespace, 'symbol');
      symbol.id = 'ic-' + alias;
      symbol.setAttribute('viewBox', icons[name].viewBox);
      symbol.setAttribute('fill', 'currentColor');
      symbol.setAttribute('stroke', 'none');
      symbol.setAttribute('data-icon-source', 'Font Awesome Free 6.7.2 / ' + name);
      symbol.innerHTML = icons[name].body;
      defs.append(symbol);
    }
  }
  window.ArchitectureIcons = {svg, install};
})();
'''
    bundle = bundle.replace('ICON_DATA', json.dumps(icons, ensure_ascii=False))
    bundle = bundle.replace('ALIAS_DATA', json.dumps(ALIASES))
    (OUTPUT / 'icons.js').write_text(bundle)
    print(f'Bundled {len(icons)} Font Awesome Free {VERSION} icons with upstream license and hashes')


if __name__ == '__main__':
    main()
