#!/usr/bin/env python3
"""Refresh the offline architecture page's catalog without loading any plugin."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'docs/architecture/catalog.js'


def main():
    relative = 'configs/plugins.json'
    groups = json.loads((ROOT / relative).read_text())
    plugins = [dict(kind=kind, name=name, origin='统一插件目录', registry=relative, **spec)
               for kind, entries in groups.items() for name, spec in entries.items()]
    commands = json.loads((ROOT / 'configs/components/commands.json').read_text())
    directories = []
    sections = ('src', 'src/embodied', 'src/embodied/applications', 'src/embodied/devices',
                'src/embodied/control', 'src/embodied/devices/robots', 'src/embodied/devices/inputs',
                'apps', 'docs', 'scripts', 'assets', 'configs', 'configs/environments')
    for parent in (ROOT, *(ROOT / name for name in sections)):
        for path in sorted(parent.iterdir()):
            if path.is_dir() and not path.name.startswith(('.', '__')) and path != ROOT / 'third_party':
                directories.append(path.relative_to(ROOT).as_posix() + '/')
    data = {
        'plugins': plugins,
        'commands': [{'name': name, **spec} for name, spec in commands['commands'].items()],
        'environments': commands['environments'],
        'profiles': [p.stem for p in sorted((ROOT / 'configs/workbench').glob('*.json'))],
        'directories': directories,
        'sources': [relative, 'configs/components/commands.json'],
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('// Generated by scripts/docs/build_architecture.py. No SDK imports.\n'
                      + 'window.ARCHITECTURE_CATALOG = '
                      + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
    print(f'{OUTPUT.relative_to(ROOT)}: {len(plugins)} plugins, {len(data["commands"])} commands')


if __name__ == '__main__':
    main()
