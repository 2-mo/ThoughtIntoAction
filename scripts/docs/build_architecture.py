#!/usr/bin/env python3
"""Refresh the offline architecture page's catalog without loading any plugin."""
from __future__ import annotations

import json
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'docs/architecture/catalog.js'


def main():
    plugins = {}
    for relative, origin in (
        ('configs/plugins.toml', '原有注册表'),
        ('control/config/components.json', 'arx 工作台'),
        ('configs/components/migrated.json', '迁入组件'),
    ):
        path = ROOT / relative
        groups = tomllib.loads(path.read_text()) if path.suffix == '.toml' else json.loads(path.read_text())
        for kind, entries in groups.items():
            for name, spec in entries.items():
                plugins[(kind, name)] = dict(kind=kind, name=name, origin=origin,
                                             registry=relative, **spec)
    commands = json.loads((ROOT / 'configs/components/commands.json').read_text())
    directories = []
    for parent in (ROOT, ROOT / 'src'):
        for path in sorted(parent.iterdir()):
            if path.is_dir() and not path.name.startswith(('.', '__')):
                directories.append(path.relative_to(ROOT).as_posix() + '/')
    data = {
        'plugins': list(plugins.values()),
        'commands': [{'name': name, **spec} for name, spec in commands['commands'].items()],
        'environments': commands['environments'],
        'profiles': [p.stem for p in sorted((ROOT / 'configs/workbench').glob('*.json'))],
        'directories': directories,
        'sources': ['configs/plugins.toml', 'control/config/components.json',
                    'configs/components/migrated.json', 'configs/components/commands.json'],
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('// Generated by scripts/docs/build_architecture.py. No SDK imports.\n'
                      + 'window.ARCHITECTURE_CATALOG = '
                      + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
    print(f'{OUTPUT.relative_to(ROOT)}: {len(plugins)} plugins, {len(data["commands"])} commands')


if __name__ == '__main__':
    main()
