"""Small structural contracts; implementations need not inherit project base classes."""

from typing import Any, Protocol


class ArmBackend(Protocol):
    robot_config: Any
    def get_joint_positions(self) -> Any: ...  # Six joints + gripper width, SI units.
    def get_joint_velocities(self) -> Any: ...
    def set_joint_positions(self, positions) -> bool: ...
    def set_catch_pos(self, position: float) -> bool: ...
    def set_to_damping(self) -> None: ...
    def close(self) -> None: ...


class ServiceDevice(ArmBackend, Protocol):
    def set_control_enabled(self, enabled: bool) -> None: ...
    def set_motion_limit(self, speed: float) -> None: ...
    def get_recording_snapshot(self) -> dict: ...  # Required for hardware devices.


class PoseInput(Protocol):
    def get_pose_by_name(self, name: str) -> Any: ...  # xyz + xyzw quaternion.
    def get_key_value_by_name(self, name: str) -> float: ...
    def get_button_state_by_name(self, name: str) -> bool: ...
    def get_motion_tracker_data(self) -> dict: ...
    def close(self) -> None: ...


class StateSink(Protocol):
    def update(self, actual, target=None) -> None: ...
    def path(self, name: str, points, color: int) -> None: ...
    def close(self) -> None: ...


class Viewer(Protocol):
    def accept(self, packet: dict) -> None: ...
    def set_stream_error(self, message: str) -> None: ...
    def close(self) -> None: ...


class Camera(Protocol):
    metadata: dict
    def __enter__(self) -> "Camera": ...
    def read(self) -> dict: ...  # image, frame_number, device/host timestamps.
    def __exit__(self, *exc) -> None: ...
